<?php
/**
 * Message persistence.
 *
 * @package ChatChi
 */

namespace ChatChi\Database\Repositories;

use ChatChi\Database\DatabaseException;
use ChatChi\Database\Table;
use ChatChi\Models\Message;

defined( 'ABSPATH' ) || exit;

/**
 * Reads and writes the messages table.
 *
 * @method Message|null        find( int $id )
 * @method array<int, Message> find_many( int[] $ids )
 */
final class MessageRepository extends Repository {

	private const MAX_LIMIT = 100;

	/**
	 * {@inheritDoc}
	 */
	protected function table_name(): string {
		return Table::MESSAGES;
	}

	/**
	 * {@inheritDoc}
	 */
	protected function columns(): array {
		return array(
			'conversation_id' => '%d',
			'sender_type'     => '%s',
			'sender_id'       => '%d',
			'body'            => '%s',
			'client_id'       => '%s',
			'attachment_id'   => '%d',
			'created_at'      => '%s',
			'read_at'         => '%s',
		);
	}

	/**
	 * {@inheritDoc}
	 */
	protected function hydrate( array $row ): Message {
		return Message::from_row( $row );
	}

	/**
	 * Stores a message.
	 *
	 * When a client ID is given, sending the same message twice (e.g. a
	 * network retry) returns the stored message instead of a duplicate.
	 *
	 * @param int         $conversation_id Conversation ID.
	 * @param string      $sender_type     One of Message::sender_types().
	 * @param int         $sender_id       Visitor or agent ID; 0 for system messages.
	 * @param string      $body            Message text, already sanitized.
	 * @param string|null $client_id       Optional UUID generated by the client.
	 * @param bool|null   $created         Set to false when an existing message was returned.
	 *
	 * @throws \InvalidArgumentException When an argument is invalid.
	 * @throws DatabaseException         When the insert fails.
	 */
	public function create( int $conversation_id, string $sender_type, int $sender_id, string $body, ?string $client_id = null, ?bool &$created = null ): Message {
		$created = false;

		if ( $conversation_id <= 0 ) {
			throw new \InvalidArgumentException( 'Message conversation ID must be a positive integer.' );
		}

		if ( ! in_array( $sender_type, Message::sender_types(), true ) ) {
			throw new \InvalidArgumentException( sprintf( 'Unknown message sender type "%s".', $sender_type ) );
		}

		if ( null !== $client_id ) {
			// wp_is_uuid() only accepts lowercase hex.
			$client_id = strtolower( $client_id );

			if ( ! wp_is_uuid( $client_id ) ) {
				throw new \InvalidArgumentException( 'Message client ID must be a UUID.' );
			}

			$existing = $this->find_by_client_id( $conversation_id, $client_id );

			if ( $existing ) {
				return $existing;
			}
		}

		try {
			$id = $this->insert_row(
				array(
					'conversation_id' => $conversation_id,
					'sender_type'     => $sender_type,
					'sender_id'       => max( 0, $sender_id ),
					'body'            => $body,
					'client_id'       => $client_id,
					'created_at'      => $this->now(),
					'read_at'         => null,
				)
			);
		} catch ( DatabaseException $e ) {
			// A concurrent request may have inserted the same client ID first.
			$existing = null !== $client_id ? $this->find_by_client_id( $conversation_id, $client_id ) : null;

			if ( $existing ) {
				return $existing;
			}

			throw $e;
		}

		$created = true;

		$message = $this->find( $id );

		if ( ! $message instanceof Message ) {
			throw new DatabaseException( sprintf( 'ChatChi message %d could not be read after insert.', $id ) );
		}

		return $message;
	}

	/**
	 * Finds a message by its client-generated ID.
	 *
	 * @param int    $conversation_id Conversation ID.
	 * @param string $client_id       Client UUID.
	 */
	public function find_by_client_id( int $conversation_id, string $client_id ): ?Message {
		if ( $conversation_id <= 0 || '' === $client_id ) {
			return null;
		}

		$rows = $this->select(
			$this->db->prepare(
				"SELECT * FROM {$this->table()} WHERE conversation_id = %d AND client_id = %s LIMIT 1",
				$conversation_id,
				strtolower( $client_id )
			)
		);

		return $rows ? $rows[0] : null;
	}

	/**
	 * Lists a conversation's messages in chronological order.
	 *
	 * - after_id > 0: messages newer than that ID (polling for new messages).
	 * - otherwise: the latest messages, optionally older than before_id
	 *   (initial load and "load earlier messages").
	 *
	 * @param int $conversation_id Conversation ID.
	 * @param int $after_id        Return messages with a greater ID.
	 * @param int $before_id       Return messages with a smaller ID.
	 * @param int $limit           Maximum messages, 1–100.
	 * @return Message[]
	 */
	public function list_for_conversation( int $conversation_id, int $after_id = 0, int $before_id = 0, int $limit = 50 ): array {
		if ( $conversation_id <= 0 ) {
			return array();
		}

		$limit = min( self::MAX_LIMIT, max( 1, $limit ) );

		if ( $after_id > 0 ) {
			return $this->select(
				$this->db->prepare(
					"SELECT * FROM {$this->table()} WHERE conversation_id = %d AND id > %d ORDER BY id ASC LIMIT %d",
					$conversation_id,
					$after_id,
					$limit
				)
			);
		}

		if ( $before_id > 0 ) {
			$sql = $this->db->prepare(
				"SELECT * FROM {$this->table()} WHERE conversation_id = %d AND id < %d ORDER BY id DESC LIMIT %d",
				$conversation_id,
				$before_id,
				$limit
			);
		} else {
			$sql = $this->db->prepare(
				"SELECT * FROM {$this->table()} WHERE conversation_id = %d ORDER BY id DESC LIMIT %d",
				$conversation_id,
				$limit
			);
		}

		return array_reverse( $this->select( $sql ) );
	}

	/**
	 * Marks messages from one side of the conversation as read.
	 *
	 * Example: when an agent opens a conversation, mark the visitor's messages.
	 *
	 * @param int    $conversation_id Conversation ID.
	 * @param string $sender_type     Whose messages to mark.
	 * @param int    $up_to_id        Only mark messages up to this ID; 0 for all.
	 * @return int Number of messages marked.
	 *
	 * @throws \InvalidArgumentException When the sender type is unknown.
	 */
	public function mark_read( int $conversation_id, string $sender_type, int $up_to_id = 0 ): int {
		if ( ! in_array( $sender_type, Message::sender_types(), true ) ) {
			throw new \InvalidArgumentException( sprintf( 'Unknown message sender type "%s".', $sender_type ) );
		}

		if ( $conversation_id <= 0 ) {
			return 0;
		}

		$sql    = "UPDATE {$this->table()} SET read_at = %s WHERE conversation_id = %d AND sender_type = %s AND read_at IS NULL";
		$params = array( $this->now(), $conversation_id, $sender_type );

		if ( $up_to_id > 0 ) {
			$sql     .= ' AND id <= %d';
			$params[] = $up_to_id;
		}

		return $this->execute( $this->db->prepare( $sql, $params ) );
	}

	/**
	 * Counts unread messages from one side, for several conversations at once.
	 *
	 * @param int[]  $conversation_ids Conversation IDs.
	 * @param string $sender_type      Whose unread messages to count.
	 * @return array<int, int> Counts keyed by conversation ID; missing IDs have none.
	 */
	public function count_unread( array $conversation_ids, string $sender_type ): array {
		$ids = $this->sanitize_ids( $conversation_ids );

		if ( ! $ids ) {
			return array();
		}

		$placeholders = implode( ',', array_fill( 0, count( $ids ), '%d' ) );

		$rows = $this->db->get_results(
			$this->db->prepare(
				"SELECT conversation_id, COUNT(*) AS total FROM {$this->table()} WHERE conversation_id IN ({$placeholders}) AND sender_type = %s AND read_at IS NULL GROUP BY conversation_id",
				array_merge( $ids, array( $sender_type ) )
			),
			ARRAY_A
		);
		$this->assert_no_error( 'count of ' . $this->table_name() );

		$counts = array();
		foreach ( (array) $rows as $row ) {
			$counts[ (int) $row['conversation_id'] ] = (int) $row['total'];
		}

		return $counts;
	}

	/**
	 * Links a file to a message.
	 *
	 * @param int $id            Message ID.
	 * @param int $attachment_id Attachment ID.
	 * @return bool Whether the row changed.
	 */
	public function attach( int $id, int $attachment_id ): bool {
		return $this->update_row( $id, array( 'attachment_id' => max( 0, $attachment_id ) ) );
	}

	/**
	 * Counts one side's messages in a conversation.
	 *
	 * @param int    $conversation_id Conversation ID.
	 * @param string $sender_type     Whose messages to count.
	 */
	public function count_from( int $conversation_id, string $sender_type ): int {
		$count = $this->db->get_var(
			$this->db->prepare(
				"SELECT COUNT(*) FROM {$this->table()} WHERE conversation_id = %d AND sender_type = %s",
				$conversation_id,
				$sender_type
			)
		);
		$this->assert_no_error( 'count of ' . $this->table_name() );

		return (int) $count;
	}
}
